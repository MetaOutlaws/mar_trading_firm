"""Bounds for the capped Bybit kline pull. No network."""
from datetime import datetime, timezone

import pytest

from research.cipher_forward.fetch_tape import (
    ENDPOINT,
    BybitBlocked,
    FetchWindowError,
    assert_request_bounds,
    fetch_series,
    fetch_tape,
    filter_kline_rows,
    frame_from_rows,
    write_series,
)
from research.cipher_forward.tape import (
    HARD_END_MS,
    HOUR_MS,
    WINDOW_START_MS,
    YEAR_2026_MS,
    read_bar_file,
)


def _ms(year, month, day, hour=0):
    return int(datetime(year, month, day, hour, tzinfo=timezone.utc).timestamp() * 1000)


def _row(stamp, price='10'):
    return [str(stamp), price, '11', '9', price, '1', '2']


class _Response:
    def __init__(self, status, payload):
        self.status_code = status
        self._payload = payload
        self.headers = {'content-type': 'application/json'}
        self.text = payload if isinstance(payload, str) else ''

    def json(self):
        if isinstance(self._payload, str):
            raise ValueError('not json')
        return self._payload


def test_request_bounds_allow_the_cap_and_reject_the_next_millisecond():
    assert_request_bounds(WINDOW_START_MS, HARD_END_MS)
    assert HARD_END_MS == _ms(2025, 12, 31, 23)
    with pytest.raises(FetchWindowError, match='23:00:00'):
        assert_request_bounds(WINDOW_START_MS, HARD_END_MS + 1)
    with pytest.raises(FetchWindowError, match='23:00:00'):
        assert_request_bounds(WINDOW_START_MS, _ms(2026, 1, 1))
    with pytest.raises(FetchWindowError, match='2022-01-01'):
        assert_request_bounds(WINDOW_START_MS + HOUR_MS, HARD_END_MS)
    with pytest.raises(FetchWindowError, match='2022-01-01'):
        assert_request_bounds(WINDOW_START_MS - 1, HARD_END_MS)


def test_filter_keeps_the_last_hour_and_drops_both_sides():
    rows = [
        _row(WINDOW_START_MS - 1),
        _row(WINDOW_START_MS),
        _row(HARD_END_MS),
        _row(HARD_END_MS + 1),
        _row(YEAR_2026_MS),
    ]
    kept, dropped = filter_kline_rows(rows)
    assert dropped == 3
    assert [int(row[0]) for row in kept] == [WINDOW_START_MS, HARD_END_MS]


def test_write_drops_late_and_early_rows_before_the_file(tmp_path):
    rows = [
        _row(HARD_END_MS - HOUR_MS),
        _row(HARD_END_MS),
        _row(HARD_END_MS + 1),
        _row(YEAR_2026_MS),
        _row(WINDOW_START_MS - HOUR_MS),
    ]
    frame, dropped = frame_from_rows(rows)
    assert dropped == 3
    written = write_series(tmp_path, 'BTCUSDT', '1h', frame)
    loaded = read_bar_file(tmp_path / 'BTCUSDT.parquet', '1h')
    assert list(map(int, loaded['open_time_ms'])) == [HARD_END_MS - HOUR_MS, HARD_END_MS]
    assert written['rows'] == 2
    assert written['last_open'] == '2025-12-31T23:00:00Z'
    assert written['sha256']


def test_pages_keep_start_at_the_window_and_end_at_or_before_the_cap():
    calls = []

    def transport(params):
        calls.append(dict(params))
        assert params['category'] == 'linear'
        assert params['limit'] == 1000
        assert params['interval'] == '60'
        end = int(params['end'])
        start = int(params['start'])
        assert_request_bounds(start, end)
        rows = []
        for offset in range(1000):
            stamp = end - offset * HOUR_MS
            if stamp < WINDOW_START_MS:
                break
            rows.append(_row(stamp))
            if len(rows) == 1000 and offset == 0:
                pass
        # Two full pages, then a short page, so the walk actually paginates.
        if len(calls) >= 3:
            rows = rows[:10]
        return _Response(200, {'retCode': 0, 'result': {'list': rows}})

    pulled = fetch_series(
        'BTCUSDT', '1h', transport, {'next': 0.0}, lambda _delay: None, lambda: 0.0)
    assert calls
    assert all(int(call['start']) == WINDOW_START_MS for call in calls)
    assert all(int(call['end']) <= HARD_END_MS for call in calls)
    assert int(calls[0]['end']) == HARD_END_MS
    assert int(calls[1]['end']) < int(calls[0]['end'])
    assert int(pulled['frame']['open_time_ms'].max()) <= HARD_END_MS
    assert int(pulled['frame']['open_time_ms'].min()) >= WINDOW_START_MS
    assert ENDPOINT == 'https://api.bybit.com/v5/market/kline'


def test_403_stops_before_the_next_symbol(tmp_path):
    seen = []

    def transport(params):
        seen.append(params['symbol'])
        step = HOUR_MS if params['interval'] == '60' else 4 * HOUR_MS
        if params['symbol'] == 'ETHUSDT':
            response = _Response(403, '')
            response.text = 'HTTP 403 Generated by CloudFront'
            response.headers = {'server': 'CloudFront', 'content-type': 'text/html'}
            return response
        return _Response(200, {'retCode': 0, 'result': {'list': [
            _row(WINDOW_START_MS), _row(WINDOW_START_MS + step),
        ]}})

    with pytest.raises(BybitBlocked, match='403'):
        fetch_tape(
            tmp_path,
            symbols=('BTCUSDT', 'ETHUSDT'),
            transport=transport,
            sleep=lambda _delay: None,
            now=lambda: 0.0,
            reuse_valid=False,
        )
    assert seen[0] == 'BTCUSDT'
    assert 'ETHUSDT' in seen
    assert seen.count('ETHUSDT') == 1
