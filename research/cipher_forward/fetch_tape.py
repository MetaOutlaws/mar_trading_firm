"""Capped public Bybit kline pull for the pre-2026 1h/4h tape.

This is not BybitOHLCV.fetch. That client defaults its end to now. Every
request here uses start 2022-01-01 00:00:00 UTC and an end at or before
2025-12-31 23:00:00 UTC. A returned row outside that window is dropped
before anything is written.

The only host is https://api.bybit.com. A 403, a geo block, or a
CloudFront body stops the pull. Nothing is retried through a proxy or a
mirror. trust_env is off, so HTTP_PROXY is not used.
"""
from __future__ import annotations

import hashlib
import time
from datetime import datetime, timezone
from pathlib import Path

from .tape import (
    FOUR_HOUR_MS,
    HARD_END,
    HARD_END_MS,
    HOUR_MS,
    TIMEFRAMES,
    WINDOW_START,
    WINDOW_START_MS,
    TapeRejected,
    read_bar_file,
    required_symbols,
)

ENDPOINT = 'https://api.bybit.com/v5/market/kline'
CATEGORY = 'linear'
LIMIT = 1000
PACE_S = 0.25
INTERVALS = {'1h': '60', '4h': '240'}
STEPS = {'1h': HOUR_MS, '4h': FOUR_HOUR_MS}
ATTEMPTS = 6
BACKOFF_S = (1, 2, 4, 8, 16, 32)


class FetchWindowError(ValueError):
    """A request start or end left the hard window."""


class BybitBlocked(RuntimeError):
    """Bybit answered 403, or the body is a CloudFront or geo block.

    The pull stops. It does not switch host, proxy, or mirror.
    """


class FetchFailed(RuntimeError):
    """A symbol page failed after the paced retries."""


def assert_request_bounds(start_ms: int, end_ms: int) -> None:
    """Start is the window open. End is never after 2025-12-31 23:00:00 UTC."""
    if isinstance(start_ms, bool) or not isinstance(start_ms, int):
        raise FetchWindowError('start is not an int millisecond')
    if isinstance(end_ms, bool) or not isinstance(end_ms, int):
        raise FetchWindowError('end is not an int millisecond')
    if start_ms != WINDOW_START_MS:
        raise FetchWindowError(
            f'start {start_ms} is not 2022-01-01 00:00:00 UTC ({WINDOW_START_MS})')
    if end_ms > HARD_END_MS:
        raise FetchWindowError(
            f'end {end_ms} is after 2025-12-31 23:00:00 UTC ({HARD_END_MS})')
    if end_ms < WINDOW_START_MS:
        raise FetchWindowError('end is before 2022-01-01 00:00:00 UTC')


def _stamp(row) -> int:
    try:
        return int(row[0])
    except (TypeError, ValueError, IndexError) as exc:
        raise TapeRejected('kline row has no open time') from exc


def filter_kline_rows(rows) -> tuple[list, int]:
    """Drop any row whose open is outside the inclusive hard window.

    Exactly 2025-12-31 23:00:00 UTC stays. One millisecond later is dropped.
    A 2026 open is dropped. The caller still must not request that end.
    """
    kept = []
    dropped = 0
    for row in rows:
        stamp = _stamp(row)
        if stamp < WINDOW_START_MS or stamp > HARD_END_MS:
            dropped += 1
            continue
        kept.append(row)
    return kept, dropped


def _iso(ms: int) -> str:
    return datetime.fromtimestamp(ms / 1000, timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')


def frame_from_rows(rows):
    """One ascending frame. Outside rows are absent. Turnover is not invented."""
    import pandas as pd
    kept, dropped = filter_kline_rows(rows)
    by_open: dict[int, list] = {}
    for row in kept:
        if len(row) < 7:
            raise TapeRejected('kline row is shorter than the Bybit layout')
        by_open[int(row[0])] = row
    if not by_open:
        empty = pd.DataFrame(columns=[
            'open_time_ms', 'open', 'high', 'low', 'close', 'volume', 'turnover'])
        return empty, dropped
    ordered = [by_open[stamp] for stamp in sorted(by_open)]
    frame = pd.DataFrame(ordered, columns=[
        'open_time_ms', 'open', 'high', 'low', 'close', 'volume', 'turnover'])
    frame['open_time_ms'] = frame['open_time_ms'].astype('int64')
    for name in ('open', 'high', 'low', 'close', 'volume', 'turnover'):
        frame[name] = frame[name].astype('float64')
    return frame, dropped


def _blocked_text(response) -> str | None:
    body = response.text[:2000]
    lowered = body.lower()
    headers = {}
    for key, value in response.headers.items():
        if key.lower() in {
            'server', 'via', 'x-cache', 'x-amz-cf-id', 'x-amz-cf-pop',
            'x-amzn-errortype', 'content-type',
        }:
            headers[key] = value
    text = f'HTTP {response.status_code} headers={headers} body={body}'
    if response.status_code == 403:
        return text
    if 'cloudfront' in lowered or 'generated by cloudfront' in lowered:
        return text
    return None


def _pace(pacer: dict, sleep, now) -> None:
    delay = pacer['next'] - now()
    if delay > 0:
        sleep(delay)
    pacer['next'] = now() + PACE_S


def _page(transport, symbol: str, interval: str, start_ms: int, end_ms: int) -> list:
    """One public page. Bounds are asserted before the request is built."""
    assert_request_bounds(start_ms, end_ms)
    params = {
        'category': CATEGORY,
        'symbol': symbol,
        'interval': interval,
        'start': start_ms,
        'end': end_ms,
        'limit': LIMIT,
    }
    response = transport(params)
    blocked = _blocked_text(response)
    if blocked is not None:
        raise BybitBlocked(blocked)
    if response.status_code in {429, 500, 502, 503, 504}:
        raise FetchFailed(f'HTTP {response.status_code} for {symbol} {interval}')
    if response.status_code != 200:
        raise FetchFailed(
            f'HTTP {response.status_code} for {symbol} {interval}: {response.text[:500]}')
    try:
        payload = response.json()
    except ValueError as exc:
        raise FetchFailed(f'{symbol} {interval} response was not JSON') from exc
    ret = payload.get('retCode')
    if ret != 0:
        message = payload.get('retMsg', '')
        if ret == 10001:
            raise TapeRejected(f'{symbol}: {message}')
        raise FetchFailed(f'Bybit retCode={ret}: {message}')
    return list(payload.get('result', {}).get('list', []) or [])


def _page_with_retry(transport, symbol, interval, start_ms, end_ms, pacer, sleep, now) -> list:
    last: Exception | None = None
    for attempt in range(ATTEMPTS):
        _pace(pacer, sleep, now)
        try:
            return _page(transport, symbol, interval, start_ms, end_ms)
        except BybitBlocked:
            raise
        except TapeRejected:
            raise
        except Exception as exc:
            last = exc
            if attempt + 1 >= ATTEMPTS:
                break
            sleep(BACKOFF_S[min(attempt, len(BACKOFF_S) - 1)])
    raise FetchFailed(f'Failed to fetch {symbol} {interval} ending {end_ms}: {last}')


def fetch_series(symbol: str, timeframe: str, transport, pacer, sleep, now) -> dict:
    """Pull one symbol and timeframe. Start stays the window open on every page."""
    if timeframe not in INTERVALS:
        raise FetchWindowError(f'unsupported timeframe {timeframe}')
    interval = INTERVALS[timeframe]
    step = STEPS[timeframe]
    end_ms = HARD_END_MS
    collected: list = []
    requests = 0
    dropped = 0
    while True:
        assert_request_bounds(WINDOW_START_MS, end_ms)
        page = _page_with_retry(
            transport, symbol, interval, WINDOW_START_MS, end_ms, pacer, sleep, now)
        requests += 1
        if not page:
            break
        stamps = [_stamp(row) for row in page]
        oldest = min(stamps)
        kept, page_dropped = filter_kline_rows(page)
        dropped += page_dropped
        collected.extend(kept)
        if len(page) < LIMIT:
            break
        next_end = oldest - step
        if next_end < WINDOW_START_MS:
            break
        if next_end >= end_ms:
            raise FetchWindowError(
                f'{symbol} {timeframe} pagination did not move before {end_ms}')
        end_ms = next_end
        assert_request_bounds(WINDOW_START_MS, end_ms)
    frame, frame_dropped = frame_from_rows(collected)
    return dict(frame=frame, requests=requests, dropped_outside_window=dropped + frame_dropped)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b''):
            digest.update(chunk)
    return digest.hexdigest()


def write_series(directory: Path, symbol: str, timeframe: str, frame) -> dict:
    """Write one parquet file and return the manifest row. Does not fetch."""
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f'{symbol}.parquet'
    if frame.empty:
        if path.exists():
            path.unlink()
        return dict(
            rows=0, first_open=None, last_open=None, sha256=None,
            path=None, status='no_bars',
        )
    frame.to_parquet(path, index=False)
    checked = read_bar_file(path, timeframe)
    first = int(checked['open_time_ms'].iloc[0])
    last = int(checked['open_time_ms'].iloc[-1])
    assert_request_bounds(WINDOW_START_MS, min(last, HARD_END_MS))
    if last > HARD_END_MS or first < WINDOW_START_MS:
        raise FetchWindowError(f'{symbol} {timeframe} wrote a bar outside the window')
    return dict(
        rows=int(len(checked)),
        first_open=_iso(first),
        last_open=_iso(last),
        sha256=_sha256(path),
        path=str(path),
        status='ok',
    )


def _valid_file(path: Path, timeframe: str) -> dict | None:
    if not path.is_file():
        return None
    try:
        frame = read_bar_file(path, timeframe)
    except (OSError, ValueError):
        return None
    if frame.empty:
        return None
    first = int(frame['open_time_ms'].iloc[0])
    last = int(frame['open_time_ms'].iloc[-1])
    if first < WINDOW_START_MS or last > HARD_END_MS:
        return None
    return dict(
        rows=int(len(frame)),
        first_open=_iso(first),
        last_open=_iso(last),
        sha256=_sha256(path),
        path=str(path),
        status='ok',
        reused=True,
        requests=0,
        dropped_outside_window=0,
    )


def fetch_tape(
    out_dir: Path,
    *,
    symbols: tuple[str, ...] | None = None,
    transport=None,
    client=None,
    sleep=time.sleep,
    now=time.monotonic,
    reuse_valid: bool = True,
) -> dict:
    """Fetch every symbol at 1h and 4h into out_dir/{1h,4h}/SYMBOL.parquet.

    A block raises BybitBlocked and leaves later symbols unrequested.
    """
    names = tuple(symbols) if symbols is not None else required_symbols()
    if not names:
        raise FetchWindowError('no symbols')
    out_dir = Path(out_dir)
    own_client = client is None and transport is None
    http = None
    if transport is None:
        import httpx
        http = client or httpx.Client(
            timeout=30.0,
            follow_redirects=False,
            trust_env=False,
            headers={'User-Agent': 'mar-trading-firm-cipher-forward-tape/1'},
        )

        def transport(params, http=http):
            return http.get(ENDPOINT, params=params)

    pacer = {'next': 0.0}
    started = now()
    manifest_symbols: dict[str, dict] = {}
    errors: list[str] = []
    try:
        for symbol in names:
            manifest_symbols[symbol] = {}
            for timeframe in TIMEFRAMES:
                folder = out_dir / timeframe
                folder.mkdir(parents=True, exist_ok=True)
                path = folder / f'{symbol}.parquet'
                if reuse_valid:
                    existing = _valid_file(path, timeframe)
                    if existing is not None:
                        manifest_symbols[symbol][timeframe] = existing
                        continue
                try:
                    pulled = fetch_series(symbol, timeframe, transport, pacer, sleep, now)
                    row = write_series(folder, symbol, timeframe, pulled['frame'])
                    row['requests'] = pulled['requests']
                    row['dropped_outside_window'] = pulled['dropped_outside_window']
                    row['reused'] = False
                    manifest_symbols[symbol][timeframe] = row
                    if row['status'] != 'ok':
                        errors.append(f'{symbol} {timeframe}: {row["status"]}')
                except BybitBlocked:
                    raise
                except (TapeRejected, FetchWindowError, FetchFailed, OSError) as exc:
                    errors.append(f'{symbol} {timeframe}: {exc}')
                    manifest_symbols[symbol][timeframe] = dict(
                        rows=None, first_open=None, last_open=None, sha256=None,
                        status='error', error=str(exc),
                    )
    finally:
        if own_client:
            http.close()
    manifest = dict(
        label='SEEN',
        source=ENDPOINT,
        category=CATEGORY,
        auth=False,
        limit=LIMIT,
        pace_seconds=PACE_S,
        intervals=dict(INTERVALS),
        window_start=WINDOW_START.strftime('%Y-%m-%dT%H:%M:%SZ'),
        window_end=HARD_END.strftime('%Y-%m-%dT%H:%M:%SZ'),
        end_never_after=HARD_END.strftime('%Y-%m-%dT%H:%M:%SZ'),
        start_is=WINDOW_START.strftime('%Y-%m-%dT%H:%M:%SZ'),
        bybit_ohlcv_fetch_reused=False,
        proxy=False,
        mirror=False,
        symbols=manifest_symbols,
        complete=not errors,
        errors=errors,
        elapsed_seconds=now() - started,
    )
    if errors:
        raise FetchFailed('; '.join(errors))
    return manifest


def manifest_document(manifest: dict) -> dict:
    """The committed manifest. Paths on this machine stay out of it."""
    symbols = {}
    for symbol, frames in manifest['symbols'].items():
        symbols[symbol] = {}
        for timeframe, row in frames.items():
            symbols[symbol][timeframe] = dict(
                rows=row.get('rows'),
                first_open=row.get('first_open'),
                last_open=row.get('last_open'),
                sha256=row.get('sha256'),
                requests=row.get('requests'),
                dropped_outside_window=row.get('dropped_outside_window', 0),
                reused=row.get('reused', False),
                status=row.get('status'),
            )
    return dict(
        label=manifest['label'],
        source=manifest['source'],
        category=manifest['category'],
        auth=manifest['auth'],
        limit=manifest['limit'],
        pace_seconds=manifest['pace_seconds'],
        intervals=manifest['intervals'],
        window_start=manifest['window_start'],
        window_end=manifest['window_end'],
        end_never_after=manifest['end_never_after'],
        start_is=manifest['start_is'],
        bybit_ohlcv_fetch_reused=False,
        complete=manifest['complete'],
        errors=list(manifest['errors']),
        elapsed_seconds=manifest['elapsed_seconds'],
        symbols=symbols,
    )
